from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parent
TARGET = ROOT / "Ambiance/xfwm4"


def xpm(name, rows):
    assert rows and rows[0] and all(len(row) == len(rows[0]) for row in rows), name
    colors = list(dict.fromkeys(pixel for row in rows for pixel in row))
    assert all(color == "None" or re.fullmatch(r"#[0-9a-fA-F]{6}", color)
               for color in colors), (name, colors)
    symbols = " .+@#$%&*=-;:>,<123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
    assert len(colors) <= len(symbols)
    palette = dict(zip(colors, symbols))
    lines = [f"{len(rows[0])} {len(rows)} {len(colors)} 1"]
    lines += [f"{palette[color]} c {color}" for color in colors]
    lines += ["".join(palette[color] for color in row) for row in rows]
    contents = '/* XPM */\n/* Generated by generate-xfwm.py; GPL-3.0-only. */\n'
    contents += 'static const char * const image[] = {\n'
    contents += ',\n'.join('"' + line + '"' for line in lines) + '\n};\n'
    (TARGET / (name + ".xpm")).write_text(contents)


def gradient(top, bottom, height=28):
    start = tuple(bytes.fromhex(top))
    end = tuple(bytes.fromhex(bottom))
    return ["#" + "".join(f"{round(a + (b-a)*y/(height-1)):02x}"
                           for a, b in zip(start, end)) for y in range(height)]


def generate():
    TARGET.mkdir(parents=True, exist_ok=True)
    for state, top, highlight in [("active", "4e4d49", "696863"),
                                   ("inactive", "44433f", "504f4b")]:
        colors = gradient(top, "3c3b37")
        colors[0] = "#" + highlight
        for part in range(1, 6):
            xpm(f"title-{part}-{state}", [[color] for color in colors])
        for side in ["left", "right"]:
            rows = [[color] * 6 for color in colors]
            for y, inset in enumerate([5, 3, 2, 1, 1]):
                for x in range(inset):
                    rows[y][x if side == "left" else 5-x] = "None"
            xpm(f"top-{side}-{state}", rows)
            edge = ["#33322f", "#3c3b37", "#3c3b37"]
            xpm(f"{side}-{state}", [edge if side == "left" else edge[::-1]])
            corner = [["#3c3b37"] * 3 for _ in range(3)]
            corner[-1] = ["#33322f"] * 3
            xpm(f"bottom-{side}-{state}", corner)
        xpm(f"bottom-{state}", [["#3c3b37"], ["#3c3b37"], ["#33322f"]])

    for action, original in [("close", "close"), ("hide", "minimize"),
                             ("maximize", "maximize"), ("maximize-toggled", "unmaximize"),
                             ("menu", "menu")]:
        for state, suffix in [("active", "focused_normal"), ("inactive", "unfocused"),
                              ("prelight", "focused_prelight"), ("pressed", "focused_pressed")]:
            if original == "menu":
                filename = "menu_prelight.png" if state in {"prelight", "pressed"} else "menu.png"
            else:
                filename = f"{original}_{suffix}.png"
            source = ROOT / "Ambiance/metacity-1" / filename
            width, height = struct.unpack(">II", source.read_bytes()[16:24])
            name = f"{action}-{state}"
            xpm(name, [["None"] * width for _ in range(height)])
            link = TARGET / (name + ".png")
            if link.exists() or link.is_symlink():
                link.unlink()
            link.symlink_to(Path("../metacity-1") / filename)

    for action in ["shade", "shade-toggled", "stick", "stick-toggled"]:
        for state in ["active", "inactive", "prelight", "pressed"]:
            face = {"active": "#605d58", "inactive": "#494843",
                    "prelight": "#807d78", "pressed": "#3c3b37"}[state]
            ink = "#807d78" if state == "inactive" else "#dfdbd2"
            rows = [["None"] * 19 for _ in range(19)]
            for y in range(19):
                for x in range(19):
                    distance = (x-9)**2 + (y-9)**2
                    if distance <= 64:
                        rows[y][x] = "#33322f" if distance >= 49 else face
                    if action.startswith("shade"):
                        dy = (12-y) if action.endswith("toggled") else (y-6)
                        glyph = 0 <= dy <= 3 and abs(x-9) == dy
                    else:
                        glyph = ((y == 7 and 7 <= x <= 11) or (8 <= y <= 10 and x in {8, 10})
                                 or (y == 11 and 7 <= x <= 11) or (y in {12, 13} and x == 9))
                        if action.endswith("toggled") and 8 <= x <= 10 and 8 <= y <= 10:
                            glyph = True
                    if glyph:
                        rows[y][x] = ink
            xpm(f"{action}-{state}", rows)


if __name__ == "__main__":
    generate()
